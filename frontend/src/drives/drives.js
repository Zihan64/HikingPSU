export function mapsUrl(drive) {
  const params = new URLSearchParams({ api: '1', origin: CAMPUS, destination: drive.destination, travelmode: 'driving' })
  if (drive.waypoints?.length) params.set('waypoints', drive.waypoints.join('|'))
  return `https://www.google.com/maps/dir/?${params}`
}

export function formatDuration(min) {
  const h = Math.floor(min / 60), m = min % 60
  return h ? `${h} h${m ? ` ${m} min` : ''}` : `${m} min`
}

const ORDER = { short: 0, half: 1, full: 2 }

export function filterDrives(drives, { length = 'all', query = '', sort = 'time' }) {
  const q = query.trim().toLowerCase()
  const out = drives.filter(d => (length === 'all' || d.length === length) &&
    (!q || [d.name, d.roads, d.summary, TYPES[d.type].label, ...d.stops].join(' ').toLowerCase().includes(q)))
  const by = {
    time: (a, b) => ORDER[a.length] - ORDER[b.length] || a.minutes - b.minutes,
    distance: (a, b) => a.miles - b.miles,
    name: (a, b) => a.name.localeCompare(b.name),
  }[sort] || (() => 0)
  return [...out].sort(by)
}
